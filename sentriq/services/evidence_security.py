"""Evidence: what type it is served as, whether it is intact, and whether it is
safe to keep.

Four rules, all of which used to be missing or advisory:

* The media type served to a browser comes from the file's extension, never from
  the ``Content-Type`` the uploader claimed. The claim is still recorded (it is
  part of what the analyst filed) but it is not trusted for serving.
* The SHA-256 recorded at upload is checked every time the file is read. A file
  that changed on disk is refused and the refusal is audited — silent tampering
  is worse than a visible outage.
* An optional external scanner (ClamAV by convention) runs on upload. With
  ``EVIDENCE_SCAN_REQUIRED=1`` a broken scanner blocks the upload instead of
  letting an unscanned file through.
* Optional AES-256-GCM encryption at rest, keyed from the environment. It covers
  the case that actually happens — a stolen backup or data directory — not a
  compromised host, where the key is in memory anyway. Say that plainly rather
  than implying more.

The module imports ``config`` as a module so the key can be swapped in a test.
"""

import base64
import binascii
import hashlib
import logging
import mimetypes
import os
import pathlib
import shlex
import subprocess
import tempfile

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from .. import config

logger = logging.getLogger("sentriq.evidence")

MAGIC = b"SENTRIQ-ENC1"
NONCE_BYTES = 12
KEY_BYTES = 32

# Every extension the upload allow-list accepts, mapped once so the answer does
# not depend on the host's mime database.
MEDIA_TYPES = {
    ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ".csv": "text/csv",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".txt": "text/plain",
    ".log": "text/plain",
    ".json": "application/json",
    ".pdf": "application/pdf",
    ".pcap": "application/vnd.tcpdump.pcap",
    ".pcapng": "application/vnd.tcpdump.pcap",
}


class EvidenceError(Exception):
    """Rejected or unreadable evidence. The message is safe to show an analyst."""


# ---------------------------------------------------------------------------
# Serving
# ---------------------------------------------------------------------------

def derive_media_type(stored_name: str) -> str:
    """The media type to answer with, from the extension on disk.

    ``stored_name`` is generated by this application (alert id, random token,
    extension), so the extension is ours, not the uploader's. The client-supplied
    content type is kept in the database as a record of what was submitted.

    The table is explicit rather than left to ``mimetypes``: that reads the host's
    mime database, which differs between the Alpine image and a developer's
    Ubuntu box, and a download whose type changes with the host is a bug waiting
    to be reported. Anything not listed falls back to the system table, then to
    a generic binary type.
    """
    extension = pathlib.Path(stored_name).suffix.lower()
    if extension in MEDIA_TYPES:
        return MEDIA_TYPES[extension]
    guessed, _ = mimetypes.guess_type(f"evidence{extension}")
    return guessed or "application/octet-stream"


def verify_digest(content: bytes, expected: str) -> bool:
    """True when the bytes on disk still hash to what was recorded at upload."""
    if not expected:
        return False
    return hashlib.sha256(content).hexdigest() == expected.lower()


# ---------------------------------------------------------------------------
# Encryption at rest
# ---------------------------------------------------------------------------

def encryption_enabled() -> bool:
    return bool(config.EVIDENCE_ENCRYPTION_KEY)


def _key() -> bytes:
    raw = (config.EVIDENCE_ENCRYPTION_KEY or "").strip()
    if not raw:
        raise EvidenceError("Evidence encryption is not configured.")
    try:
        key = bytes.fromhex(raw) if len(raw) == KEY_BYTES * 2 else base64.b64decode(raw, validate=True)
    except (binascii.Error, ValueError) as error:
        raise EvidenceError("EVIDENCE_ENCRYPTION_KEY is not valid base64 or hex.") from error
    if len(key) != KEY_BYTES:
        raise EvidenceError("EVIDENCE_ENCRYPTION_KEY must decode to 32 bytes (AES-256).")
    return key


def seal(content: bytes, stored_name: str) -> bytes:
    """Encrypt for storage, binding the ciphertext to this file's stored name."""
    if not encryption_enabled():
        return content
    nonce = os.urandom(NONCE_BYTES)
    sealed = AESGCM(_key()).encrypt(nonce, content, stored_name.encode())
    return MAGIC + nonce + sealed


def unseal(content: bytes, stored_name: str) -> bytes:
    """Decrypt if sealed; return plaintext untouched for files from before this."""
    if not content.startswith(MAGIC):
        return content
    if not encryption_enabled():
        raise EvidenceError(
            "This evidence file is encrypted and EVIDENCE_ENCRYPTION_KEY is not set."
        )
    body = content[len(MAGIC):]
    nonce, sealed = body[:NONCE_BYTES], body[NONCE_BYTES:]
    try:
        return AESGCM(_key()).decrypt(nonce, sealed, stored_name.encode())
    except InvalidTag as error:
        raise EvidenceError(
            "This evidence file could not be decrypted: the key does not match, "
            "or the file was modified."
        ) from error


def is_sealed(content: bytes) -> bool:
    return content.startswith(MAGIC)


# ---------------------------------------------------------------------------
# Malware scanning
# ---------------------------------------------------------------------------

def scan_bytes(content: bytes, filename: str) -> None:
    """Run the configured scanner over the bytes, before they are stored.

    The command is taken from configuration and split with shlex, so no shell is
    involved; ``{}`` is replaced by the temporary file's path. Exit code 1 means
    "infected" by the ClamAV convention, anything else non-zero is a scanner
    failure.
    """
    command = (config.EVIDENCE_SCAN_COMMAND or "").strip()
    if not command:
        return

    with tempfile.NamedTemporaryFile(prefix="sentriq-scan-", delete=True) as handle:
        handle.write(content)
        handle.flush()
        parts = [handle.name if part == "{}" else part for part in shlex.split(command)]
        if handle.name not in parts:
            parts.append(handle.name)
        try:
            result = subprocess.run(
                parts, capture_output=True, text=True,
                timeout=config.EVIDENCE_SCAN_TIMEOUT, check=False,
            )
        except (OSError, subprocess.SubprocessError) as error:
            if config.EVIDENCE_SCAN_REQUIRED:
                raise EvidenceError(
                    f"The malware scanner could not run ({error}); this deployment "
                    "refuses unscanned evidence."
                ) from error
            logger.error("Malware scan failed for %s: %s", filename, error)
            return

    if result.returncode == 1:
        detail = (result.stdout or result.stderr or "").strip().splitlines()
        raise EvidenceError(
            f"{filename} failed the malware scan"
            + (f": {detail[-1][:200]}" if detail else ".")
        )
    if result.returncode != 0:
        message = (result.stderr or result.stdout or "").strip()[:200]
        if config.EVIDENCE_SCAN_REQUIRED:
            raise EvidenceError(
                f"The malware scanner returned {result.returncode} for {filename} "
                f"({message}); this deployment refuses unscanned evidence."
            )
        logger.error("Malware scan of %s returned %s: %s", filename, result.returncode, message)
